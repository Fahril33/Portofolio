-- Public read (portfolio is a public website)
create policy "hero_section: public read" on public.hero_section for select using (true);
create policy "about_section: public read" on public.about_section for select using (true);
create policy "social_links: public read" on public.social_links for select using (true);
create policy "showcases: public read" on public.showcases for select using (true);
create policy "skill_categories: public read" on public.skill_categories for select using (true);
create policy "skill_items: public read" on public.skill_items for select using (true);
create policy "app_configs: public read portfolio" on public.app_configs
for select
using (app = 'portfolio');

